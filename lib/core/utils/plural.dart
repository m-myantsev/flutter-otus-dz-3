///  Выбирает форму существительного для числа [n] по правилам русского языка
///
/// - [one] — форма для 1, например минута
/// - [few] — форма для 2–4, например минуты
/// - [many] — форма для остальных, например минут
///
/// ```dart
/// plural(1, one: 'минута', few: 'минуты', many: 'минут'); // 'минута'
/// plural(2, one: 'минута', few: 'минуты', many: 'минут'); // 'минуты'
/// plural(11, one: 'минута', few: 'минуты', many: 'минут'); // 'минут'
/// ```
String plural(int n, {required String one, required String few, required String many}) {
  return switch ((n % 100, n % 10)) {
    (>= 11 && <= 14, _) => many,
    (_, 1) => one,
    (_, >= 2 && <= 4) => few,
    _ => many,
  };
}
